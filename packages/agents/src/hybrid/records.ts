// ---- asset lineage ---------------------------------------------------------------------------------------------------------------

/** Where an asset really comes from. A template render is NEVER labelled AI_GENERATED, even when its picture is. */
export const ASSET_ORIGINS = ['AI_GENERATED', 'TEMPLATE_RENDERED', 'USER_UPLOADED', 'BRAND_ASSET', 'LICENSED_ASSET', 'FALLBACK'] as const;
export type AssetOrigin = (typeof ASSET_ORIGINS)[number];

export const AssetRights = z.object({
  basis: z.enum(['generated_for_user', 'original_template', 'user_provided', 'licensed', 'none']),
  note: z.string().max(240),
});
export type AssetRights = z.infer<typeof AssetRights>;

/** The lineage fields every asset may carry (all optional: campaigns saved before Hybrid Production have none and are read through originOf). */
export const AssetLineage = z.object({
  origin: z.enum(ASSET_ORIGINS).optional(),
  templateId: z.string().nullable().optional(),
  templateVersion: z.number().nullable().optional(),
  /** Every asset this one was built from: the original AI image, brand images, the logo. */
  sourceAssetIds: z.array(z.string()).optional(),
  rights: AssetRights.nullable().optional(),
});

export interface LineageSubject {
  kind: 'image' | 'layout';
  source: string;
  origin?: AssetOrigin;
}

/** The origin of an asset, derived for assets saved before origins existed. */
export function originOf(a: LineageSubject): AssetOrigin {
  if (a.origin) return a.origin;
  if (a.kind === 'image') return a.source === 'ai_image' ? 'AI_GENERATED' : 'FALLBACK';
  return 'TEMPLATE_RENDERED';
}

export const RIGHTS_BY_ORIGIN: Record<AssetOrigin, AssetRights> = {
  AI_GENERATED: { basis: 'generated_for_user', note: 'Generated by the image model on the user\'s own provider account; the provider\'s terms apply. A conceptual marketing visual, not a photograph of a real place, product or person.' },
  TEMPLATE_RENDERED: { basis: 'original_template', note: 'Composed locally from a LaunchPilot-original template and the listed source assets; it inherits the rights of those assets.' },
  USER_UPLOADED: { basis: 'user_provided', note: 'Provided by the user, who confirms the right to use it.' },
  BRAND_ASSET: { basis: 'user_provided', note: 'The project\'s own brand asset, provided by the user.' },
  LICENSED_ASSET: { basis: 'licensed', note: 'Licensed by the user; the license terms are the user\'s to keep.' },
  FALLBACK: { basis: 'none', note: 'A deterministic stand-in made without an image model (brand colors only). Not an AI image and not a photograph.' },
};

