import { INestApplication } from '@nestjs/common';
import { PrismaClient } from '@prisma/client';
import { existsSync } from 'fs';
import { resolve } from 'path';
import JSZip from 'jszip';
import { CampaignPackage } from '@launchpilot/agents';
import { FakeOpenAI, type FakeOpenAIOptions } from '@launchpilot/agents/dist/testing/fake-openai';
import { makePng } from '@launchpilot/agents/dist/testing/fixtures';
import { allEvents, configureOpenAi, createApp, createProject, loginUser, registerUser, sleep, waitForTerminal, type TestUser } from './helpers';

// F4 Creative Production end to end: HTTP API -> NestJS -> real Mozaik runtime (six participants, the Fixer created at run
// time) -> fake OpenAI text AND image APIs -> PostgreSQL + project file storage -> ZIP export. Nothing leaves the machine and
// no image is ever generated by a real model here.
describe('Creative Production (real Mozaik agents, fake text + image APIs, persisted assets)', () => {
  let app: INestApplication;
  let db: PrismaClient;
  let fake: FakeOpenAI;
  let previousUrl: string | undefined;
  const KEY = 'sk-test-CREATE2E1234567890abcdefghij';
  const MODEL = 'gpt-test-mini';
  const IMAGE_MODEL = 'gpt-image-test';
  const MODELS = ['gpt-test-mini', 'gpt-test-large', 'text-embedding-test', IMAGE_MODEL];

  async function useFake(options?: FakeOpenAIOptions) {
    if (fake) await fake.close();
    fake = await new FakeOpenAI({ models: MODELS, ...options }).start();
    process.env.LAUNCHPILOT_OPENAI_BASE_URL = fake.url;
  }

  async function readyUser(label: string, key = KEY, projectName = 'Deep Diving School') {
    const user = await registerUser(app, label);
    const projectId = await createProject(user, projectName);
    await user.agent.put(`/projects/${projectId}/intake`).send({ productName: projectName, shortDescription: 'Scuba diving courses for beginners in Novi Sad', targetMarket: 'Novi Sad, Serbia', preferredLanguage: 'en' }).expect(200);
    await configureOpenAi(user, key, MODEL);
    return { user, projectId };
  }

  const start = (u: TestUser, projectId: string, body: object = {}) => u.agent.post(`/projects/${projectId}/runs/creative-production`).send(body);
  const preflight = (u: TestUser, projectId: string, body: object = {}) => u.agent.post(`/projects/${projectId}/runs/creative-production/preflight`).send(body);

  /** F1 -> F2 -> F3 through the API on the fake, so F4 builds on REAL stored reports of the same project. */
  async function withChain(label: string, key = KEY, projectName = 'Deep Diving School') {
    const ctx = await readyUser(label, key, projectName);
    const f1 = await waitForTerminal(ctx.user, (await ctx.user.agent.post(`/projects/${ctx.projectId}/runs/product-discovery`).send({}).expect(201)).body.id, 30_000);
    expect(f1.status).toBe('COMPLETED');
    const f2 = await waitForTerminal(ctx.user, (await ctx.user.agent.post(`/projects/${ctx.projectId}/runs/marketing-audit`).send({}).expect(201)).body.id, 30_000);
    expect(f2.status).toBe('COMPLETED');
    const f3 = await waitForTerminal(ctx.user, (await ctx.user.agent.post(`/projects/${ctx.projectId}/runs/market-strategy`).send({ maxScouts: 2 }).expect(201)).body.id, 40_000);
    expect(f3.status).toBe('COMPLETED');
    return { ...ctx, f1ReportId: f1.reportId as string, auditId: f2.auditId as string, strategyId: f3.strategyId as string };
  }

  beforeAll(async () => {
    previousUrl = process.env.LAUNCHPILOT_OPENAI_BASE_URL;
    app = await createApp();
    db = new PrismaClient();
  });
  beforeEach(async () => {
    await useFake();
  });
  afterAll(async () => {
    await fake.close();
    process.env.LAUNCHPILOT_OPENAI_BASE_URL = previousUrl;
    await app.close();
    await db.$disconnect();
  });

  it('refuses to start without a completed F3, with a text model as image model, with an image model the key does not list, or with invalid limits; never bills for a refusal', async () => {
    const { user, projectId } = await readyUser('cre-nof3');
    const none = await start(user, projectId).expect(422);
    expect(none.body.message).toMatch(/completed Market Research & Strategy \(F3\)/);
    await start(user, projectId, { strategyId: 'does-not-exist' }).expect(404);
    await start(user, projectId, { imageModel: 'gpt-4.1-mini' }).expect(400); // not even a gpt-image id
    await start(user, projectId, { concepts: 9 }).expect(400);
    await start(user, projectId, { channels: ['myspace'] }).expect(400);
    await start(user, projectId, { maxRegenerations: 99 }).expect(400);
    await start(user, projectId, { imageQuality: 'ultra' }).expect(400);
    expect(fake.requests.filter((r) => r.path.endsWith('/responses') || r.path.endsWith('/images/generations'))).toHaveLength(0);
    expect(await db.campaignRun.count({ where: { userId: user.id, mode: 'creative_production' } })).toBe(0);
    expect(await db.creativeCampaign.count({ where: { projectId } })).toBe(0);
  }, 60_000);

  it('runs the whole F1 -> F2 -> F3 -> F4 chain: six participants, real image requests on the user key, persisted assets, a valid package, a working export', async () => {
    const { user, projectId, f1ReportId, auditId, strategyId } = await withChain('cre-happy');
    // an image model the key does not list is refused BEFORE anything starts (GET /models is free)
    await useFake({ models: MODELS.filter((m) => m !== IMAGE_MODEL) });
    const missing = await start(user, projectId, { imageModel: IMAGE_MODEL }).expect(422);
    expect(missing.body.message).toMatch(/not available to your OpenAI key/);
    // a shut-down model is refused even when the key still LISTS it; "auto" skips it and uses a current one
    await useFake({ models: [...MODELS, 'gpt-image-1'] });
    const retired = await start(user, projectId, { imageModel: 'gpt-image-1' }).expect(422);
    expect(retired.body.message).toMatch(/shut down gpt-image-1 on 2026-10-23/);
    const autoPre = (await preflight(user, projectId, { imageModel: 'auto', concepts: 1 }).expect(200)).body;
    expect(autoPre.settings.imageModel).toBe(IMAGE_MODEL);
    expect(autoPre.imageModel).toMatchObject({ mode: 'auto', requested: 'auto', available: true });
    expect(fake.requests.filter((r) => r.path.endsWith('/images/generations'))).toHaveLength(0);
    await useFake();

    // preflight: exact chain, effective settings and expected counts; spends nothing
    const pre = (await preflight(user, projectId, { imageModel: IMAGE_MODEL, concepts: 2, channels: ['instagram', 'facebook'] }).expect(200)).body;
    expect(pre.chain).toMatchObject({ f1ReportId, f2AuditId: auditId, f3StrategyId: strategyId });
    expect(pre.settings).toMatchObject({ model: MODEL, imageModel: IMAGE_MODEL, imageQuality: 'low', maxImages: 2, maxRegenerations: 0, maxRepairRounds: 2, maxModelCalls: 16 });
    expect(pre.estimate.imageRequests).toMatchObject({ planned: 2, max: 2, regenerationEnabled: false });
    expect(pre.estimate.layouts.planned).toBe(8);
    expect(pre.imageModel.available).toBe(true);
    expect(fake.requests.filter((r) => r.path.endsWith('/responses') || r.path.endsWith('/images/generations'))).toHaveLength(0);

    fake.requests.length = 0;
    const started = (await start(user, projectId, { imageModel: IMAGE_MODEL, concepts: 2, channels: ['instagram', 'facebook'] }).expect(201)).body;
    expect(started).toMatchObject({ mode: 'creative_production', label: 'Creative Production', status: 'RUNNING', provider: 'openai' });
    expect(started.campaignId).toBeNull(); // not yet known in the launch response
    const done = await waitForTerminal(user, started.id, 60_000);
    expect(done.status).toBe('COMPLETED');
    expect(done.campaignId).toBeTruthy();

    // the fake saw: text calls on the chosen model, exactly 2 image requests on the chosen image model, all with THIS user's key
    const imageCalls = fake.imageCalls();
    expect(imageCalls).toHaveLength(2);
    for (const r of imageCalls) {
      expect(r.authorization).toBe(`Bearer ${KEY}`);
      expect(r.body).toMatchObject({ model: IMAGE_MODEL, quality: 'low', n: 1 });
    }
    for (const r of fake.requests.filter((x) => x.path.endsWith('/responses'))) {
      expect(r.authorization).toBe(`Bearer ${KEY}`);
      expect(r.body).toMatchObject({ model: MODEL, store: false });
    }

    const other = await registerUser(app, 'cre-other');

    // the saved campaign
    const full = (await user.agent.get(`/campaigns/${done.campaignId}`).expect(200)).body;
    expect(full).toMatchObject({ projectId, runId: started.id, f1ReportId, f2AuditId: auditId, f3StrategyId: strategyId, status: 'completed', model: MODEL, imageModel: IMAGE_MODEL, schemaVersion: 1 });
    const parsed = CampaignPackage.safeParse(full.package);
    expect(parsed.success).toBe(true);
    const pkg = parsed.data!;
    expect(pkg).toMatchObject({ id: done.campaignId, projectId, runId: started.id, f1ReportId, f2ReportId: auditId, f3StrategyId: strategyId });
    expect(pkg.concepts).toHaveLength(2);
    expect(pkg.imageAssets.filter((a) => a.kind === 'image' && a.source === 'ai_image')).toHaveLength(2);
    expect(pkg.channelLayouts.length).toBeGreaterThanOrEqual(4);
    expect(pkg.landingContent).toBeTruthy();
    expect(['approved', 'approved_with_notes']).toContain(pkg.approval.status);
    expect(JSON.stringify(full)).not.toContain(KEY);
    expect(JSON.stringify(full)).not.toContain('iVBORw0KGgo'); // no binary in the JSON

    // assets: rows in the database, files in project storage, served only through the authenticated endpoint
    const rows = await db.campaignAsset.findMany({ where: { campaignId: done.campaignId } });
    expect(rows).toHaveLength(pkg.imageAssets.length);
    const assets = (await user.agent.get(`/campaigns/${done.campaignId}/assets`).expect(200)).body;
    expect(assets.items).toHaveLength(rows.length);
    const layout = assets.items.find((a: any) => a.kind === 'layout');
    expect(layout.url).toBe(`/campaigns/${done.campaignId}/assets/${layout.id}/file`);
    const file = await user.agent.get(layout.url).expect(200);
    expect(file.headers['content-type']).toMatch(/^image\/png/);
    expect(file.headers['x-content-type-options']).toBe('nosniff');
    expect(file.headers['cache-control']).toMatch(/no-store/);
    expect(Buffer.from(file.body).length).toBe(layout.bytes);
    const row = rows.find((r) => r.id === layout.id)!;
    expect(existsSync(resolve(process.cwd(), process.env.UPLOAD_DIR ?? './uploads', row.filePath))).toBe(true);
    expect(row.filePath.startsWith(`${projectId}/`)).toBe(true);

    // the landing page preview: a self-contained document with a strict CSP, every model string escaped
    const preview = await user.agent.get(`/campaigns/${done.campaignId}/landing-preview`).expect(200);
    expect(preview.headers['content-type']).toMatch(/text\/html/);
    expect(preview.headers['content-security-policy']).toMatch(/default-src 'none'/);
    expect(preview.headers['x-content-type-options']).toBe('nosniff');
    expect(preview.text).toContain(pkg.landingContent!.hero.headline.replace(/&/g, '&amp;'));
    expect(preview.text).not.toMatch(/<script/);
    await other.agent.get(`/campaigns/${done.campaignId}/landing-preview`).expect(404);

    // the review view and the export
    const reviews = (await user.agent.get(`/campaigns/${done.campaignId}/reviews`).expect(200)).body;
    expect(reviews.approval.status).toBe(pkg.approval.status);
    const zipRes = await user.agent.get(`/campaigns/${done.campaignId}/export`).buffer(true).parse((res, cb) => {
      const chunks: Buffer[] = [];
      res.on('data', (c: Buffer) => chunks.push(c));
      res.on('end', () => cb(null, Buffer.concat(chunks)));
    }).expect(200);
    expect(zipRes.headers['content-type']).toMatch(/application\/zip/);
    expect(zipRes.headers['content-disposition']).toMatch(/attachment; filename="deep-diving-school.*\.zip"/);
    const zip = await JSZip.loadAsync(zipRes.body as Buffer);
    const names = Object.keys(zip.files);
    expect(names).toEqual(expect.arrayContaining(['campaign.json', 'manifest.json', 'README.md', 'summary.html', 'landing/landing-preview.html']));
    const pngs = names.filter((n) => n.endsWith('.png'));
    expect(pngs.length).toBe(pkg.imageAssets.length);
    const manifest = JSON.parse(await zip.file('manifest.json')!.async('string'));
    expect(manifest.chain).toEqual({ f1ReportId, f2ReportId: auditId, f3StrategyId: strategyId });
    expect(manifest.assetsMissing).toEqual([]);
    const sample = manifest.files.find((f: any) => f.assetId === layout.id);
    expect((await zip.file(sample.path)!.async('nodebuffer')).length).toBe(layout.bytes);

    // the Mozaik view: real participants, the Fixer not created because nothing needed repair, the timeline of real events
    const analysis = (await user.agent.get(`/runs/${started.id}/creative-analysis`).expect(200)).body;
    expect(analysis).toMatchObject({ kind: 'creative', source: 'report', campaignId: done.campaignId, campaignStatus: 'completed' });
    const byName = Object.fromEntries(analysis.participants.map((p: any) => [p.agent, p.state]));
    expect(byName).toMatchObject({ Copywriter: 'done', 'Visual Creator': 'done', 'Layout Designer': 'done', 'Landing Content Builder': 'done', 'Content & Brand Reviewer': 'done', Fixer: 'skipped' });
    expect(analysis.plan.skipped.some((s: any) => s.key === 'fixer')).toBe(true);
    expect(analysis.aiCalls['Layout Designer'] ?? 0).toBe(0);
    expect(analysis.usage.total.calls).toBeGreaterThan(3);
    expect(analysis.images).toMatchObject({ model: IMAGE_MODEL, generated: 2, requestsStarted: 2 });
    const types = analysis.timeline.map((t: any) => `${t.type}@${t.participant}`);
    expect(types).toEqual(expect.arrayContaining(['copy.proposed@Copywriter', 'visual.generated@Visual Creator', 'layout.completed@Layout Designer', 'review.completed@Content & Brand Reviewer', 'campaign.completed@Creative Coordinator']));
    expect(types.filter((t: string) => t.startsWith('visual.generated'))).toHaveLength(2);
    expect(analysis.crosschecks.length).toBeGreaterThan(0);

    // the history is persisted without binaries and the campaign row was written BEFORE the run completed
    const events = await allEvents(user, started.id);
    const visual = events.filter((e) => e.eventType === 'visual.generated');
    expect(visual).toHaveLength(2);
    expect(JSON.stringify(events)).not.toContain('iVBORw0KGgo');
    expect(JSON.stringify(events)).not.toContain(KEY);
    const campaignRow = await db.creativeCampaign.findUniqueOrThrow({ where: { runId: started.id } });
    const run = await db.campaignRun.findUniqueOrThrow({ where: { id: started.id } });
    expect(campaignRow.updatedAt.getTime()).toBeLessThanOrEqual(run.completedAt!.getTime() + 5);
    expect(campaignRow.status).toBe('completed');

    // listing and ownership: another user sees nothing (404, not 403)
    const list = (await user.agent.get(`/projects/${projectId}/campaigns`).expect(200)).body;
    expect(list.items[0]).toMatchObject({ id: done.campaignId, status: 'completed', concepts: 2, generatedImages: 2 });
    await other.agent.get(`/campaigns/${done.campaignId}`).expect(404);
    await other.agent.get(`/campaigns/${done.campaignId}/assets`).expect(404);
    await other.agent.get(layout.url).expect(404);
    await other.agent.get(`/campaigns/${done.campaignId}/export`).expect(404);
    await other.agent.get(`/runs/${started.id}/creative-analysis`).expect(404);
    await other.agent.get(`/projects/${projectId}/campaigns`).expect(404);

    // a second campaign on the same strategy is a NEW row; the first is never overwritten
    const again = await waitForTerminal(user, (await start(user, projectId, { concepts: 1, channels: ['instagram'], landing: false }).expect(201)).body.id, 60_000);
    expect(again.status).toBe('COMPLETED');
    expect(again.campaignId).not.toBe(done.campaignId);
    expect((await db.creativeCampaign.findUniqueOrThrow({ where: { id: done.campaignId } })).packageJson).toEqual(full.package);
    expect((await user.agent.get(`/projects/${projectId}/campaigns`).expect(200)).body.items).toHaveLength(2);

    // survives a restart: a fresh application instance still serves the saved campaign, its files and its export
    const app2 = await createApp();
    try {
      const agent2 = await loginUser(app2, user.email);
      const after = (await agent2.get(`/campaigns/${done.campaignId}`).expect(200)).body;
      expect(after.package).toEqual(full.package);
      const file2 = await agent2.get(layout.url).expect(200);
      expect(Buffer.from(file2.body).length).toBe(layout.bytes);
      await agent2.get(`/campaigns/${done.campaignId}/export`).expect(200);
    } finally {
      await app2.close();
    }
  }, 240_000);

  it('without an image model nothing is generated: no image request, brand-colored backgrounds, an honest limitation; a supplied logo is placed on the layouts', async () => {
    const { user, projectId } = await withChain('cre-noimg');
    await user.agent.post(`/projects/${projectId}/assets`).field('type', 'logo').attach('files', await makePng(240, 100, '#ff6600'), { filename: 'logo.png', contentType: 'image/png' }).expect(201);
    fake.requests.length = 0;
    const pre = (await preflight(user, projectId, { concepts: 1 }).expect(200)).body;
    expect(pre.settings.imageModel).toBeNull();
    expect(pre.estimate.imageRequests.planned).toBe(0);
    expect(pre.brand.logo).toBe('logo.png');
    const done = await waitForTerminal(user, (await start(user, projectId, { concepts: 1 }).expect(201)).body.id, 60_000);
    expect(done.status).toBe('COMPLETED');
    expect(fake.imageCalls()).toHaveLength(0);
    const pkg = (await user.agent.get(`/campaigns/${done.campaignId}`).expect(200)).body.package as CampaignPackage;
    expect(pkg.imageAssets.filter((a) => a.kind === 'image').every((a) => a.source === 'brand_gradient')).toBe(true);
    expect(pkg.imageAssets.filter((a) => a.kind === 'layout').every((a) => a.flags.includes('logo_applied'))).toBe(true);
    expect(pkg.limitations.join(' ')).toMatch(/No image model/);
    expect(pkg.usage.images).toMatchObject({ model: null, requested: 0, generated: 0 });
    expect(pkg.imageResults).toHaveLength(1);
    expect(pkg.imageResults[0]).toMatchObject({ outcome: 'skipped', stage: 'configuration', requestAttempted: false, fallbackUsed: true });
    const analysis = (await user.agent.get(`/runs/${done.id}/creative-analysis`).expect(200)).body;
    expect(analysis.participants.find((p: any) => p.agent === 'Visual Creator').state).toBe('skipped');
    expect(analysis.brand).toMatchObject({ fromBrand: true, logo: true });
  }, 180_000);

  it('a campaign saved before per-concept image results existed gets them reconstructed from its recorded events, flagged, without touching the stored package', async () => {
    const { user, projectId } = await withChain('cre-legacy');
    await useFake({ reply: (r) => (r.agent === 'image' ? { status: 404, json: { error: { code: 'model_not_found', message: `no such model ${KEY}` } } } : undefined) });
    const done = await waitForTerminal(user, (await start(user, projectId, { imageModel: IMAGE_MODEL, concepts: 1, channels: ['instagram'] }).expect(201)).body.id, 90_000);
    expect(done.status).toBe('COMPLETED');
    const own = (await user.agent.get(`/campaigns/${done.campaignId}`).expect(200)).body.package;
    expect(own.imageResults[0]).toMatchObject({ outcome: 'failed', stage: 'provider', errorCode: 'model_unavailable', providerStatus: 404 });
    expect(own.imageResults[0].reconstructed).toBeUndefined();

    // simulate a package written by an older version: no imageResults at all
    const row = await db.creativeCampaign.findUniqueOrThrow({ where: { id: done.campaignId } });
    const { imageResults: _removed, ...legacy } = row.packageJson as Record<string, unknown>;
    await db.creativeCampaign.update({ where: { id: done.campaignId }, data: { packageJson: legacy as never } });

    const read = (await user.agent.get(`/campaigns/${done.campaignId}`).expect(200)).body.package;
    expect(read.imageResults).toHaveLength(1);
    expect(read.imageResults[0]).toMatchObject({ reconstructed: true, outcome: 'failed', requestAttempted: true, fallbackUsed: true, errorCode: 'model_unavailable' });
    expect(read.imageResults[0].explanation).toMatch(/does not exist or is not available/);
    expect(JSON.stringify(read)).not.toContain(KEY);
    // read-only: the stored package is exactly what the old version wrote
    const after = await db.creativeCampaign.findUniqueOrThrow({ where: { id: done.campaignId } });
    expect((after.packageJson as Record<string, unknown>).imageResults).toBeUndefined();
  }, 180_000);

  it('cancellation while images are being generated aborts the request, leaves no package, marks the campaign cancelled; export says so', async () => {
    const { user, projectId } = await withChain('cre-cancel');
    await useFake({ reply: (r) => (r.agent === 'image' ? { hang: true } : undefined) });
    const started = (await start(user, projectId, { imageModel: IMAGE_MODEL, concepts: 2, channels: ['instagram'] }).expect(201)).body;
    for (let i = 0; i < 400 && fake.imageCalls().length === 0; i++) await sleep(25);
    expect(fake.imageCalls().length).toBeGreaterThan(0);
    const cancelled = (await user.agent.post(`/runs/${started.id}/cancel`).expect(200)).body;
    expect(cancelled.status).toBe('CANCELLED');
    await sleep(100);
    expect(fake.imageCalls().every((c) => c.aborted)).toBe(true);
    const row = await db.creativeCampaign.findUniqueOrThrow({ where: { runId: started.id } });
    expect(row.status).toBe('cancelled');
    expect(row.packageJson).toBeNull();
    const exp = await user.agent.get(`/campaigns/${row.id}/export`).expect(409);
    expect(exp.body.message).toMatch(/no package/);
    const analysis = (await user.agent.get(`/runs/${started.id}/creative-analysis`).expect(200)).body;
    expect(analysis).toMatchObject({ source: 'events', campaignStatus: 'cancelled', status: 'CANCELLED' });
    expect(analysis.timeline.some((t: any) => t.type === 'copy.proposed')).toBe(true);
    expect(await db.campaignRun.findUniqueOrThrow({ where: { id: started.id } })).toMatchObject({ status: 'CANCELLED' });
  }, 180_000);

  it('two users running campaigns at the same time stay isolated: each request carries its own key, assets and packages never mix', async () => {
    const KEY_B = 'sk-test-CREATE2E-B-234567890abcdefghij';
    const [a, b] = await Promise.all([withChain('cre-conc-a'), withChain('cre-conc-b', KEY_B, 'TaskFlow')]);
    fake.requests.length = 0;
    const [ra, rb] = await Promise.all([start(a.user, a.projectId, { imageModel: IMAGE_MODEL, concepts: 1, channels: ['instagram'] }).expect(201), start(b.user, b.projectId, { imageModel: IMAGE_MODEL, concepts: 1, channels: ['linkedin'] }).expect(201)]);
    const [da, dbb] = await Promise.all([waitForTerminal(a.user, ra.body.id, 90_000), waitForTerminal(b.user, rb.body.id, 90_000)]);
    expect(da.status).toBe('COMPLETED');
    expect(dbb.status).toBe('COMPLETED');
    const keys = new Set(fake.requests.map((r) => r.authorization));
    expect(keys).toEqual(new Set([`Bearer ${KEY}`, `Bearer ${KEY_B}`]));
    const pa = (await a.user.agent.get(`/campaigns/${da.campaignId}`).expect(200)).body;
    const pb = (await b.user.agent.get(`/campaigns/${dbb.campaignId}`).expect(200)).body;
    expect(pa.projectId).toBe(a.projectId);
    expect(pb.projectId).toBe(b.projectId);
    expect(pa.package.channelLayouts.every((l: any) => l.channel === 'instagram')).toBe(true);
    expect(pb.package.channelLayouts.every((l: any) => l.channel === 'linkedin')).toBe(true);
    expect(await db.campaignAsset.count({ where: { campaignId: da.campaignId, projectId: { not: a.projectId } } })).toBe(0);
    await a.user.agent.get(`/campaigns/${dbb.campaignId}`).expect(404);
    expect(JSON.stringify([pa, pb])).not.toMatch(/sk-test/);
  }, 300_000);

  it('deleting the project removes the campaign rows and the stored image files', async () => {
    const { user, projectId } = await withChain('cre-delete');
    const done = await waitForTerminal(user, (await start(user, projectId, { concepts: 1, channels: ['instagram'], landing: false }).expect(201)).body.id, 60_000);
    expect(done.status).toBe('COMPLETED');
    const rows = await db.campaignAsset.findMany({ where: { campaignId: done.campaignId } });
    expect(rows.length).toBeGreaterThan(0);
    const paths = rows.map((r) => resolve(process.cwd(), process.env.UPLOAD_DIR ?? './uploads', r.filePath));
    expect(paths.every((p) => existsSync(p))).toBe(true);
    await user.agent.delete(`/projects/${projectId}`).expect(200);
    expect(await db.creativeCampaign.count({ where: { projectId } })).toBe(0);
    expect(await db.campaignAsset.count({ where: { projectId } })).toBe(0);
    expect(paths.some((p) => existsSync(p))).toBe(false);
  }, 180_000);
});
