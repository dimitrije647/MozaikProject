'use client';

import Link from 'next/link';
import { useParams, useSearchParams } from 'next/navigation';
import * as React from 'react';
import { ArrowLeft, Rocket, TriangleAlert } from 'lucide-react';
import { CampaignResult } from '@/components/campaign-result';
import { FactoryRunView, isActive } from '@/components/campaign-run';
import { CampaignSetup } from '@/components/campaign-setup';
import { EmptyState } from '@/components/empty-state';
import { Button } from '@/components/ui/button';
import { useFactoryRun, useFactoryRuns, useProject } from '@/lib/hooks';
import { COLLECTION_IDS, type CollectionId } from '@/lib/visual';
import { formatDate } from '@/lib/utils';

/** Generate Campaign: the one journey. Setup and the free plan, the live run, and the finished marketing package with its ZIP. */
export default function CampaignPage() {
  const { id } = useParams<{ id: string }>();
  const project = useProject(id);
  const runs = useFactoryRuns(id);
  // arriving from the Templates page ("Use in a campaign"): the setup opens with that collection chosen
  const wanted = useSearchParams().get('collection');
  const initialCollection = (COLLECTION_IDS as readonly string[]).includes(wanted ?? '') ? (wanted as CollectionId) : null;
  const [selected, setSelected] = React.useState<string | null>(null);
  const [setup, setSetup] = React.useState(!!initialCollection);

  const latest = runs.data?.[0];
  const shownId = selected ?? latest?.id ?? null;
  const run = useFactoryRun(shownId);
  const data = run.data ?? runs.data?.find((r) => r.id === shownId);
  const active = isActive(latest?.status);

  if (project.isLoading) return <div className="h-96 animate-pulse rounded-3xl bg-cream-200" />;
  if (!project.data) return <EmptyState icon={TriangleAlert} title="Project not found" action={<Button asChild><Link href="/projects">Back to projects</Link></Button>} />;
  const p = project.data;
  const showSetup = !active && (!latest || setup);
  const openSetup = () => {
    setSetup(true);
    setTimeout(() => document.getElementById('configure-campaign')?.scrollIntoView({ behavior: 'smooth', block: 'start' }), 50);
  };

  return (
    <div className="space-y-8">
      <Link href={`/projects/${id}`} className="inline-flex items-center gap-1.5 text-sm text-muted hover:text-ink">
        <ArrowLeft className="h-4 w-4" /> {p.name}
      </Link>

      <section className="panel-dark grain relative overflow-hidden p-8 sm:p-10">
        <div className="absolute -right-20 -top-24 h-72 w-72 rounded-full bg-accent/25 blur-3xl" />
        <div className="relative">
          <p className="text-xs font-medium uppercase tracking-[0.16em] text-accent">Generate campaign</p>
          <h1 className="mt-3 text-4xl text-cream-100 sm:text-5xl">{p.name}</h1>
          <p className="mt-3 max-w-3xl text-[15px] text-muted-dark">
            A small team of Mozaik agents researches your business, writes the strategy and the copy, finds your approved or licensed pictures and designs every visual from your template collection: social posts for X, TikTok, Facebook, Instagram and LinkedIn, web and display ads, a billboard and a flyer, in one ZIP. No image is ever generated by AI. The plan and the cost are shown first, for free.
          </p>
        </div>
      </section>

      {runs.isLoading ? (
        <div className="h-48 animate-pulse rounded-2xl bg-cream-200" />
      ) : (
        <>
          {active && <p className="text-sm text-muted">A campaign is being generated for this project. You can start another one when it has finished or was cancelled.</p>}

          {showSetup && (
            <section id="configure-campaign" aria-label="Set up the campaign" className="space-y-3">
              <h2 className="text-2xl">{latest ? 'Generate another campaign' : 'Set up the campaign'}</h2>
              <CampaignSetup
                projectId={id}
                initialCollection={initialCollection}
                onStarted={(r) => {
                  setSelected(r.id);
                  setSetup(false);
                }}
              />
            </section>
          )}

          {data && (
            <section aria-label="Campaign run" className="space-y-4">
              <div className="flex flex-wrap items-center justify-between gap-3">
                <h2 className="text-2xl">Progress</h2>
                <div className="flex flex-wrap items-center gap-3">
                  {(runs.data?.length ?? 0) > 1 && (
                    <label className="flex items-center gap-2 text-xs text-muted">
                      Campaign
                      <select aria-label="Earlier campaigns" className="rounded-lg border border-cream-300 bg-cream-50 px-2 py-1.5 text-xs text-ink" value={shownId ?? ''} onChange={(e) => setSelected(e.target.value)}>
                        {runs.data!.map((r, i) => (
                          <option key={r.id} value={r.id}>
                            {formatDate(r.createdAt)} · {r.status}
                            {i === 0 ? ' (latest)' : ''}
                          </option>
                        ))}
                      </select>
                    </label>
                  )}
                  {!active && !setup && (
                    <Button variant="outline" size="sm" onClick={openSetup}>
                      <Rocket className="h-3.5 w-3.5" /> Generate another campaign
                    </Button>
                  )}
                </div>
              </div>
              <FactoryRunView projectId={id} run={data} onRestart={openSetup} />
              {data.campaignId && (
                <div id="campaign-result" className="space-y-3">
                  <h2 className="text-2xl">Your marketing package</h2>
                  <CampaignResult campaignId={data.campaignId} />
                </div>
              )}
            </section>
          )}
        </>
      )}
    </div>
  );
}
